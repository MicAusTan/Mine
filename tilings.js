// "Shape tiles": boards where every cell IS the shape. Each builder returns raw cells
// (corner lists); finalize() works out which cells touch (share a corner) and tidies up.
import { centroid, distToPolyline } from './geom.js';

export const TILED_SHAPES = ['triangle', 'hexagon', 'pentagon', 'star', 'heptagon'];
const SQ3 = Math.sqrt(3);

function vertexIndex(tol) { // gives equal ids to points that are (nearly) the same
  const map = new Map(); let next = 0;
  return pt => {
    const bi = Math.floor(pt[0] / tol), bj = Math.floor(pt[1] / tol);
    for (let di = -1; di <= 1; di++) for (let dj = -1; dj <= 1; dj++) {
      const arr = map.get((bi + di) + ',' + (bj + dj));
      if (arr) for (const e of arr) if (Math.hypot(e.x - pt[0], e.y - pt[1]) < tol) return e.id;
    }
    const e = { x: pt[0], y: pt[1], id: next++ };
    const k = bi + ',' + bj;
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(e);
    return e.id;
  };
}

function finalize(raw, circle = null) {
  const vi = vertexIndex(1e-6), owners = new Map();
  raw.forEach((c, i) => {
    for (const p of c.corners) {
      const v = vi(p);
      if (!owners.has(v)) owners.set(v, new Set());
      owners.get(v).add(i);
    }
  });
  const nb = raw.map(() => new Set());
  for (const set of owners.values()) { // cells sharing a corner are neighbours
    const a = [...set];
    for (const x of a) for (const y of a) if (x !== y) nb[x].add(y);
  }
  // keep only the largest connected piece
  const comp = new Int32Array(raw.length).fill(-1);
  let best = -1, bestSize = 0, nc = 0;
  for (let s = 0; s < raw.length; s++) {
    if (comp[s] >= 0) continue;
    let size = 0; const st = [s]; comp[s] = nc;
    while (st.length) { const k = st.pop(); size++; for (const n of nb[k]) if (comp[n] < 0) { comp[n] = nc; st.push(n); } }
    if (size > bestSize) { bestSize = size; best = nc; }
    nc++;
  }
  const keep = [], map = new Int32Array(raw.length).fill(-1);
  raw.forEach((c, i) => { if (comp[i] === best) { map[i] = keep.length; keep.push(i); } });

  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const i of keep) for (const [x, y] of (raw[i].outline || raw[i].corners)) {
    minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }
  if (circle) {
    minX = Math.min(minX, circle.cx - circle.r); maxX = Math.max(maxX, circle.cx + circle.r);
    minY = Math.min(minY, circle.cy - circle.r); maxY = Math.max(maxY, circle.cy + circle.r);
  }
  const pad = 0.15, ox = pad - minX, oy = pad - minY;
  const cells = keep.map(i => {
    const outline = (raw[i].outline || raw[i].corners).map(([x, y]) => [x + ox, y + oy]);
    const [cx, cy] = centroid(outline);
    return { outline, cx, cy, inr: distToPolyline([cx, cy], outline) };
  });
  return {
    kind: 'poly', width: maxX - minX + 2 * pad, height: maxY - minY + 2 * pad, cells,
    neighbors: keep.map(i => [...nb[i]].map(n => map[n]).filter(n => n >= 0)),
    circle: circle ? { cx: circle.cx + ox, cy: circle.cy + oy, r: circle.r } : null,
  };
}

// All tilings are scaled so an average tile has area 1 (same as one square tile).

function triangles(w, h) {
  const a = Math.sqrt(4 / SQ3), hh = a * SQ3 / 2, raw = [];
  for (let r = 0; r < h; r++) for (let c = 0; c < w; c++) {
    const x0 = c * a / 2, y0 = r * hh;
    raw.push({ corners: (r + c) % 2 === 0
      ? [[x0 + a / 2, y0], [x0 + a, y0 + hh], [x0, y0 + hh]]
      : [[x0, y0], [x0 + a, y0], [x0 + a / 2, y0 + hh]] });
  }
  return finalize(raw);
}

function hexagons(w, h) {
  const s = Math.sqrt(2 / (3 * SQ3)), W = SQ3 * s, raw = [];
  for (let r = 0; r < h; r++) for (let c = 0; c < w; c++) {
    const x = (c + (r & 1) * 0.5) * W, y = r * 1.5 * s;
    raw.push({ corners: Array.from({ length: 6 }, (_, k) => {
      const a = Math.PI / 6 + k * Math.PI / 3;
      return [x + s * Math.cos(a), y + s * Math.sin(a)];
    }) });
  }
  return finalize(raw);
}

// Cairo tiling: congruent pentagons (angles 120,120,90,120,90; edges 1,1,1,1 and sqrt3-1).
function pentagons(w, h) {
  const b = SQ3 - 1, k = 1 / Math.sqrt(1.5);
  const P0 = [[0, 0], [b, 0], [b + .5, SQ3 / 2], [b / 2, SQ3 / 2 + .5], [-.5, SQ3 / 2]];
  const C = P0[2]; // a 4-valent corner: four rotated copies form a rosette around it
  const rot = (p, n) => { let [x, y] = [p[0] - C[0], p[1] - C[1]]; for (let i = 0; i < n; i++) [x, y] = [-y, x]; return [C[0] + x, C[1] + y]; };
  const W = w / k, H = h / k, S = Math.ceil(W / SQ3) + 4, D = Math.ceil(H / SQ3) + 4, raw = [];
  for (let s = -S; s <= S; s++) for (let d = -D; d <= D; d++) {
    if ((s + d) & 1) continue; // lattice generated by (sqrt3, sqrt3) and (sqrt3, -sqrt3)
    for (let r = 0; r < 4; r++) {
      const poly = P0.map(p => rot(p, r)).map(([x, y]) => [x + SQ3 * s, y + SQ3 * d]);
      const [cx, cy] = centroid(poly);
      if (cx < 0 || cy < 0 || cx > W || cy > H) continue;
      raw.push({ corners: poly.map(([x, y]) => [x * k, y * k]) });
    }
  }
  return finalize(raw);
}

// Four-pointed stars (tips touching) alternating with fat eight-sided "gap" tiles.
function stars(w, h) {
  const a = 0.42, k = 1 / Math.SQRT2, W = w / k, H = h / k, raw = [];
  const poly = (cx, cy, t) => [[1, 0], [t, t], [0, 1], [-t, t], [-1, 0], [-t, -t], [0, -1], [t, -t]]
    .map(([x, y]) => [(cx + x) * k, (cy + y) * k]);
  for (let j = 0; j * 2 <= H; j++) for (let i = 0; i * 2 <= W; i++) {
    raw.push({ corners: poly(i * 2, j * 2, a) });                                   // star
    if (i * 2 + 1 <= W && j * 2 + 1 <= H) raw.push({ corners: poly(i * 2 + 1, j * 2 + 1, 1 - a) }); // filler
  }
  return finalize(raw);
}

// ---- hyperbolic heptagons: {7,3} in the Poincare disk ----
function geodCircle(A, B) { // circle orthogonal to the unit circle through A and B (null if a diameter)
  const det = A[0] * B[1] - A[1] * B[0];
  if (Math.abs(det) < 1e-12) return null;
  const a = A[0] * A[0] + A[1] * A[1] + 1, b = B[0] * B[0] + B[1] * B[1] + 1;
  const cx = (a * B[1] - b * A[1]) / (2 * det), cy = (A[0] * b - B[0] * a) / (2 * det);
  return { cx, cy, rho2: cx * cx + cy * cy - 1 };
}
function reflector(A, B) { // reflection across the geodesic through A and B
  const c = geodCircle(A, B);
  if (!c) {
    const l = Math.hypot(A[0], A[1]) || Math.hypot(B[0], B[1]);
    const dx = (A[0] || B[0]) / l, dy = (A[1] || B[1]) / l;
    return z => { const t = z[0] * dx + z[1] * dy; return [2 * t * dx - z[0], 2 * t * dy - z[1]]; };
  }
  return z => {
    const dx = z[0] - c.cx, dy = z[1] - c.cy, k = c.rho2 / (dx * dx + dy * dy);
    return [c.cx + k * dx, c.cy + k * dy];
  };
}
function geodesicPoints(A, B, K) { // K points from A towards B along the geodesic (B excluded)
  const c = geodCircle(A, B), pts = [];
  if (!c) { for (let t = 0; t < K; t++) pts.push([A[0] + (B[0] - A[0]) * t / K, A[1] + (B[1] - A[1]) * t / K]); return pts; }
  const rho = Math.sqrt(c.rho2), a0 = Math.atan2(A[1] - c.cy, A[0] - c.cx);
  let d = Math.atan2(B[1] - c.cy, B[0] - c.cx) - a0;
  while (d > Math.PI) d -= 2 * Math.PI;
  while (d < -Math.PI) d += 2 * Math.PI;
  for (let t = 0; t < K; t++) pts.push([c.cx + rho * Math.cos(a0 + d * t / K), c.cy + rho * Math.sin(a0 + d * t / K)]);
  return pts;
}

function heptagons(rings) {
  const p = 7, q = 3;
  const R = Math.acosh(1 / Math.tan(Math.PI / p) / Math.tan(Math.PI / q)), r0 = Math.tanh(R / 2);
  const base = Array.from({ length: p }, (_, k) => {
    const a = -Math.PI / 2 + 2 * Math.PI * k / p;
    return [r0 * Math.cos(a), r0 * Math.sin(a)];
  });
  const idx = vertexIndex(1e-7), seen = new Set([idx([0, 0])]);
  const cells = [{ c: [0, 0], v: base, depth: 0 }];
  for (let head = 0; head < cells.length; head++) {
    const cell = cells[head];
    if (cell.depth >= rings) continue;
    for (let e = 0; e < p; e++) {
      const f = reflector(cell.v[e], cell.v[(e + 1) % p]);
      const c2 = f(cell.c), id = idx(c2);
      if (seen.has(id)) continue;
      seen.add(id);
      cells.push({ c: c2, v: cell.v.map(f), depth: cell.depth + 1 });
    }
  }
  const raw = cells.map(cell => {
    const outline = [];
    for (let e = 0; e < p; e++) {
      const A = cell.v[e], B = cell.v[(e + 1) % p];
      outline.push(...geodesicPoints(A, B, Math.hypot(A[0] - B[0], A[1] - B[1]) < 0.03 ? 4 : 8));
    }
    return { corners: cell.v, outline };
  });
  // scale so the smallest tile is still comfortably clickable
  let minInr = Infinity;
  for (const c of raw) minInr = Math.min(minInr, distToPolyline(centroid(c.outline), c.outline));
  let s = 0.34 / minInr;
  if (s > 30) s = 30; // very large boards: keep the disk a sane size (rim tiles get small; zoom in)
  for (const c of raw) { c.corners = c.corners.map(([x, y]) => [x * s, y * s]); c.outline = c.outline.map(([x, y]) => [x * s, y * s]); }
  return finalize(raw, { cx: 0, cy: 0, r: s });
}

export function buildTiledLayout(shape, w, h) {
  switch (shape) {
    case 'triangle': return triangles(w, h);
    case 'hexagon': return hexagons(w, h);
    case 'pentagon': return pentagons(w, h);
    case 'star': return stars(w, h);
    case 'heptagon': return heptagons(w);
  }
  throw new Error('no tiling for ' + shape);
}
